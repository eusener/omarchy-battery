const assert = require('node:assert/strict')
const model = require('../UsageModel.js')

assert.deepEqual(model.bars(null), [])
const samples = Array.from({length: 241}, (_, i) => ({elapsed: i * 30, percentage: 100 - i / 4}))
const bars = model.bars({elapsed: 7200, samples})
assert.ok(bars.length <= 24)
assert.deepEqual(bars[0], samples[0])
assert.deepEqual(bars.at(-1), samples.at(-1))
assert.ok(bars.every(point => samples.includes(point)))
assert.ok(bars.every((point, i) => i === 0 || point.elapsed > bars[i - 1].elapsed))
assert.equal(model.duration(9300), '2 h 35 min')
assert.equal(model.duration(45), '0 min')
assert.equal(model.duration(null), '0 min')
assert.equal(model.duration(3600, (key) => key, String), 'usageHours')
assert.deepEqual(model.average(null), {seconds: 0, count: 0})
assert.deepEqual(model.average({active: true, elapsed: 900}), {seconds: 0, count: 0})
assert.deepEqual(model.average({active: false, elapsed: 3600}), {seconds: 3600, count: 1})
assert.deepEqual(model.average({active: true, elapsed: 900, history: [{elapsed: 3600}, {elapsed: 7200}, {elapsed: 60}]}), {seconds: 5400, count: 2})
assert.deepEqual(model.average({active: false, elapsed: 120, history: [{elapsed: 1800}]}), {seconds: 1800, count: 1})
console.log('Usage chart samples, duration and average: OK')
